import argparse
import hashlib
import importlib.util
import json
import os
import re
import shutil
import zipfile
from datetime import datetime, timezone
from pathlib import Path


EXCLUDED_DIRECTORIES = {".git", "__pycache__", ".venv", "venv", "node_modules", "browser_profile", "chrome_profile"}
HEAVY_SUFFIXES = {".pt", ".pth", ".npz", ".npy", ".dat", ".zip"}
HEAVY_NAMES = {"protocol.jsonl", "updates.csv", "behavior_updates.csv"}
EXCLUDED_NAMES = {"project.private.config.json", ".env", "id_rsa", "id_ed25519", ".npmrc", ".pypirc"}
TEXT_SUFFIXES = {".py", ".js", ".ts", ".json", ".jsonl", ".md", ".html", ".txt", ".yml", ".yaml", ".csv", ".log"}
SECRET_PATTERN = re.compile(r"gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{35,}|AKIA[0-9A-Z]{16}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----")


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def storage(path):
    return "release" if path.suffix.lower() in HEAVY_SUFFIXES or path.name in HEAVY_NAMES or path.stat().st_size >= 90 * 1024 * 1024 else "git"


def excluded_file(path):
    return (path.name in EXCLUDED_NAMES or path.name.startswith(".env.") and path.name != ".env.example"
            or path.suffix.lower() in {".pyc", ".pyo", ".pem", ".key"})


def copy_sources(workspace, snapshot):
    exclusions = []
    copied = []
    for name in ("FanHua", "WemiEnv", "flappybird_rl", "文献"):
        source_root = workspace / name
        if not source_root.is_dir():
            raise FileNotFoundError(source_root)
        for directory, directories, filenames in os.walk(source_root):
            current = Path(directory)
            for child in list(directories):
                child_path = current / child
                if child in EXCLUDED_DIRECTORIES or child_path == workspace / "FanHua/publishing":
                    directories.remove(child)
                    exclusions.append({"path": child_path.relative_to(workspace).as_posix() + "/", "reason": "cache, dependency, nested Git, browser profile, or publication workspace"})
            for filename in sorted(filenames):
                source = current / filename
                relative = source.relative_to(workspace)
                if excluded_file(source):
                    exclusions.append({"path": relative.as_posix(), "reason": "local private configuration, generated bytecode, or credential filename"})
                    continue
                if source.suffix.lower() in TEXT_SUFFIXES and source.stat().st_size <= 5 * 1024 * 1024:
                    if SECRET_PATTERN.search(source.read_text(encoding="utf-8", errors="replace")):
                        raise ValueError(f"Potential credential detected; no upload performed: {relative}")
                destination = snapshot / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, destination)
                copied.append({"path": relative.as_posix(), "bytes": source.stat().st_size, "sha256": digest(source)})
    return copied, exclusions


def write_indexes(snapshot):
    runs = sorted((snapshot / "FanHua/experiments").iterdir())
    lines = ["# 历史实验索引", "", "目录名保持原始时间戳；状态来自各目录保存的 JSON，失败与中断记录一并保留。", "",
             "| 运行目录 | 保存状态 | 交互步/局数 | 说明 |", "|---|---|---|---|"]
    for run in runs:
        if not run.is_dir():
            continue
        status = "见目录记录"
        count = "—"
        for filename in ("evaluation.json", "status.json", "verification.json", "pretrain.json", "repair.json", "collection.json", "preflight.json"):
            candidate = run / filename
            if candidate.is_file():
                value = json.loads(candidate.read_text(encoding="utf-8-sig"))
                status = str(value.get("status", "passed=" + str(value["passed"]) if "passed" in value else "有记录"))
                if "global_steps" in value:
                    count = str(value["global_steps"]) + " 步"
                elif isinstance(value.get("episodes"), list):
                    count = str(len(value["episodes"])) + " 局"
                break
        role = "最终共享主线" if run.name.endswith("mainline_shared_model") else "历史验证/训练/诊断"
        if run.name in {"20261008_172006_553338_evaluate_flappybird", "20261008_200326_813205_evaluate_timberman"}:
            role = "最终冻结验收"
        elif "baseline" in run.name:
            role = "单游戏参照基线"
        lines.append(f"| [{run.name}](../FanHua/experiments/{run.name}/) | {status} | {count} | {role} |")
    (snapshot / "docs/EXPERIMENT_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    tree = ["# 项目完整目录结构", "", "保留原有相对路径；模型与重型日志需要完整 Release 包。文件逐项索引见 FILE_INDEX.md。", "", "```text", "Strong-Training/"]

    def visit(directory, prefix=""):
        children = sorted(directory.iterdir(), key=lambda child: (not child.is_dir(), child.name.lower()))
        for index, child in enumerate(children):
            last = index == len(children) - 1
            tree.append(prefix + ("└── " if last else "├── ") + child.name + ("/" if child.is_dir() else ""))
            if child.is_dir():
                visit(child, prefix + ("    " if last else "│   "))

    visit(snapshot)
    tree.extend(["```", "", "目录职责和运行方式见根 README。生成目录树时，索引文件自身可能尚未落盘；最终文件全集以 ARCHIVE_MANIFEST.json 为准。"])
    (snapshot / "docs/DIRECTORY_STRUCTURE.md").write_text("\n".join(tree) + "\n", encoding="utf-8")
    index = ["# 文件逐项索引", "", "Git 列表中的重型文件链接需要先下载完整 Release 解压到同一目录。", "", "| 路径 | 字节数 | 保存位置 |", "|---|---:|---|"]
    for path in sorted(snapshot.rglob("*")):
        if path.is_file():
            relative = path.relative_to(snapshot).as_posix()
            index.append(f"| [{relative}](../{relative}) | {path.stat().st_size} | {storage(path)} |")
    (snapshot / "docs/FILE_INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")


def build(workspace, output, template_root, archive_date):
    snapshot = output / "Strong-Training"
    if output.exists():
        raise FileExistsError(f"Use a fresh output directory: {output}")
    output.mkdir(parents=True)
    snapshot.mkdir()
    copied, exclusions = copy_sources(workspace, snapshot)
    print(f"Copied {len(copied)} source files", flush=True)
    (snapshot / "docs").mkdir()
    (snapshot / "tools").mkdir()
    shutil.copy2(snapshot / "FanHua/README.md", snapshot / "docs/HISTORICAL_FANHUA_README.md")
    templates = {
        "README.project.md": "README.md", "README.fanhua.md": "FanHua/README.md",
        "requirements-compatible.txt": "FanHua/requirements-compatible.txt",
        "PACKAGING_POLICY.md": "docs/PACKAGING_POLICY.md", "THIRD_PARTY.md": "docs/THIRD_PARTY.md",
        "gitignore.project": ".gitignore", "tools/verify_archive.py": "tools/verify_archive.py",
        "tools/prepare_portable_mainline.py": "tools/prepare_portable_mainline.py",
        "build_release.py": "tools/build_release.py",
    }
    for source, destination in templates.items():
        shutil.copy2(template_root / source, snapshot / destination)
    template_copy = snapshot / "tools/publication_templates"
    template_copy.mkdir()
    for name in ("README.project.md", "README.fanhua.md", "requirements-compatible.txt", "PACKAGING_POLICY.md", "THIRD_PARTY.md", "gitignore.project"):
        shutil.copy2(template_root / name, template_copy / name)
    (template_copy / "tools").mkdir()
    for name in ("verify_archive.py", "prepare_portable_mainline.py"):
        shutil.copy2(template_root / "tools" / name, template_copy / "tools" / name)
    shutil.copy2(template_root / "build_release.py", template_copy / "build_release.py")
    write_indexes(snapshot)
    files = []
    for path in sorted(snapshot.rglob("*")):
        if path.is_file():
            files.append({"path": path.relative_to(snapshot).as_posix(), "bytes": path.stat().st_size,
                          "sha256": digest(path), "storage": storage(path)})
    manifest = {"format_version": 1, "created_at_utc": datetime.now(timezone.utc).isoformat(),
                "repository": "SchnappiMika/Strong-Training", "private": True,
                "files": files, "original_source_files": copied, "excluded": exclusions,
                "manifest_self_included": False,
                "source_overrides": {"FanHua/README.md": "Original preserved in docs/HISTORICAL_FANHUA_README.md"},
                "total_bytes": sum(entry["bytes"] for entry in files), "training_started": False}
    (snapshot / "docs/ARCHIVE_MANIFEST.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    specification = importlib.util.spec_from_file_location("archive_verifier", snapshot / "tools/verify_archive.py")
    verifier = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(verifier)
    verification = verifier.verify(snapshot, full=True)
    print(json.dumps(verification, ensure_ascii=False), flush=True)
    archive = output / f"Strong-Training-full-{archive_date}.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6, allowZip64=True) as package:
        for path in sorted(snapshot.rglob("*")):
            if path.is_file() and "__pycache__" not in path.parts:
                package.write(path, "Strong-Training/" + path.relative_to(snapshot).as_posix())
    with zipfile.ZipFile(archive) as package:
        failed = package.testzip()
        if failed:
            raise ValueError(f"ZIP CRC check failed: {failed}")
    final = output / "shared_model_final.pt"
    shutil.copy2(snapshot / "FanHua/experiments/20261008_122246_330413_mainline_shared_model/checkpoints/latest.pt", final)
    (output / "SHA256SUMS.txt").write_text("\n".join(f"{digest(path)}  {path.name}" for path in (archive, final)) + "\n", encoding="utf-8")
    summary = {"repository_directory": str(snapshot), "archive": str(archive), "archive_bytes": archive.stat().st_size,
               "archived_files": len(files) + 1, "archived_bytes": manifest["total_bytes"],
               "git_files": sum(entry["storage"] == "git" for entry in files) + 1,
               "release_files": sum(entry["storage"] == "release" for entry in files), "verification": verification}
    (output / "build_report.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)


def main():
    parser = argparse.ArgumentParser(description="Build private Strong Training source snapshot, inventories and full Release archive")
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--date", default="20261015")
    parser.add_argument("--templates", type=Path)
    args = parser.parse_args()
    if not re.fullmatch(r"\d{8}", args.date):
        parser.error("Date must contain eight digits")
    template_root = args.templates or Path(__file__).resolve().parent
    if not (template_root / "README.project.md").exists():
        template_root = template_root / "publication_templates"
    build(args.workspace.resolve(), args.output.resolve(), template_root, args.date)


if __name__ == "__main__":
    main()
